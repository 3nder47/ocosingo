function knIcono(nombre, clase) {
  return '<svg class="kn-i' + (clase ? ' ' + clase : '') + '" viewBox="0 0 24 24" width="24" height="24" fill="none" stroke="currentColor" ' +
    'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' + (KN_LUCIDE[nombre] || KN_LUCIDE['package']) + '</svg>';
}

/* Ícono por categoría (Codex): se compara el NOMBRE de la categoría, sin acentos y en minúsculas; gana la primera
   coincidencia, así las reglas específicas van antes que "accesorio", "electrónica" y "hogar". Una categoría nueva
   sin coincidencia lleva "package" y nunca impide el alta. */
